typedef struct {
    EFI_GUID guid;
    char *name;
} Registered;

static Registered *reg;
static int nreg;

const char *guid_db_name(const EFI_GUID *g)
{
    for (int i = 0; i < nreg; i++)
        if (!memcmp(&reg[i].guid, g, sizeof(EFI_GUID)))
            return reg[i].name;
    for (size_t i = 0; i < ARRAY_SIZE(builtin); i++)
        if (!memcmp(&builtin[i].guid, g, sizeof(EFI_GUID)))
            return builtin[i].name;
    return NULL;
}

bool guid_db_find(const char *name, EFI_GUID *g)
{
    for (int i = 0; i < nreg; i++) {
        if (!strcasecmp(reg[i].name, name)) {
            *g = reg[i].guid;
            return true;
        }
    }
    for (size_t i = 0; i < ARRAY_SIZE(builtin); i++) {
        if (!strcasecmp(builtin[i].name, name)) {
            *g = builtin[i].guid;
            return true;
        }
    }
    return false;
}

bool guid_db_register(const EFI_GUID *g, const char *name)
{
    EFI_GUID other;
    if (guid_db_find(name, &other) && memcmp(&other, g, sizeof(EFI_GUID)))
        return false; /* the name is already used by another GUID */
    for (int i = 0; i < nreg; i++) {
        if (!memcmp(&reg[i].guid, g, sizeof(EFI_GUID))) {
            free(reg[i].name);
            reg[i].name = xstrdup(name);
            return true;
        }
    }
    reg = xrealloc(reg, sizeof(Registered) * (nreg + 1));
    reg[nreg].guid = *g;
    reg[nreg].name = xstrdup(name);
    nreg++;
    return true;
}

/* Name if known, otherwise the GUID in text form (buffer of 37 bytes). */
const char *guid_str(const EFI_GUID *g, char buf[37])
{
    const char *n = guid_db_name(g);
    if (n)
        return n;
    guid_format(g, buf);
    return buf;
}
